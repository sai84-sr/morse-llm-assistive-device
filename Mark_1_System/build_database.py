morse_map = {'e':'t','t':'e','a':'n','n':'a','i':'m','m':'i','s':'o','o':'s'}
kbd_map   = {'a':'s','s':'a','e':'r','r':'e','o':'p','p':'o','i':'u','u':'i'}

def generate_variations(text, count=30):
    """Generate diverse variations of a phrase to simulate paralysis Morse input."""
    vars_set = set()
    vars_set.add(text)

    words = text.split()

    # 1. Abbreviation: first letter of each word
    abbr = "".join(w[0] for w in words if w)
    if abbr: vars_set.add(abbr)
    # with spaces
    vars_set.add(" ".join(w[0] for w in words if w))

    # 2. First 2-3 letters of each word
    for n in [2, 3]:
        vars_set.add("".join(w[:n] for w in words if len(w) >= n))
        vars_set.add(" ".join(w[:n] for w in words if len(w) >= n))

    # 3. Drop vowels
    no_vowel = "".join(c for c in text if c not in "aeiou")
    if no_vowel: vars_set.add(no_vowel)
    no_vowel_sp = " ".join("".join(c for c in w if c not in "aeiou") for w in words)
    if no_vowel_sp.strip(): vars_set.add(no_vowel_sp.strip())

    # 4. Truncated versions
    for i in range(1, min(4, len(text))):
        vars_set.add(text[:-i])
        vars_set.add(text[:len(text)-i])

    # 5. Character transpositions (simulates Morse errors)
    for _ in range(5):
        t = list(text)
        if len(t) > 3:
            i = RNG.randint(0, len(t)-2)
            t[i], t[i+1] = t[i+1], t[i]
        vars_set.add("".join(t))

    # 6. Double character errors
    for _ in range(3):
        t = list(text)
        if len(t) > 2:
            i = RNG.randint(0, len(t)-1)
            t.insert(i, t[i])
        vars_set.add("".join(t))

    # 7. Morse-like substitutions
    vars_set.add("".join(morse_map.get(c, c) if RNG.random() < 0.25 else c for c in text))

    # 8. Keyboard adjacency errors
    vars_set.add("".join(kbd_map.get(c, c) if RNG.random() < 0.15 else c for c in text))

    # 9. Missing last characters
    for n in [1, 2, 3]:
        if len(text) > n + 2:
            vars_set.add(text[:-n])

    # 10. Spaced-out versions
    vars_set.add(" ".join(text))
    vars_set.add(" ".join(list(text[:min(5, len(text))])))

    # 11. Common patient phrases
    vars_set.add(f"i want {text}")
    vars_set.add(f"need {text}")
    vars_set.add(f"nd {text}")
    vars_set.add(f"give {text}")
    vars_set.add(f"giv {text}")
    vars_set.add(f"{text} please")
    vars_set.add(f"{text} pls")
    vars_set.add(f"i need {text}")

    # Clean and filter
    result = [v.strip() for v in vars_set if v and len(v.strip()) >= 1]
    return list(result)[:count]


